export function createTranslator(language: Language) {
  return (key: string, vars: Vars = {}) => {
    const value = (language === "en" ? en[key] : zh[key]) ?? zh[key] ?? key;
    return value.replace(/\{(\w+)\}/g, (_, name: string) =>
      String(vars[name] ?? `{${name}}`),
    );
  };
}
